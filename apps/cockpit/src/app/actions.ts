/**
 * Land 3 media reuse: copy a source production's assets (+ thumbnails) onto a
 * new production, keeping the same storage keys so the pipeline's skip-if-present
 * steps reuse them instead of regenerating. Only what still exists is copied —
 * so the halt keep/discard choices decide what gets reused.
 */
type DbOrTx = Db | Parameters<Parameters<Db["transaction"]>[0]>[0];
async function copyProductionMedia(
  tx: DbOrTx,
  sourceId: string,
  newId: string,
  // #96: the resolved profile the NEW production will run under, when the caller
  // knows it. Assets that the new profile forbids are not carried forward.
  opts: { dropSourcedStills?: boolean } = {},
) {
  const srcAssets = await tx.select().from(assets).where(eq(assets.productionId, sourceId));
  // Never copy the source RENDER (2026-07-19): the copy re-renders from its own
  // (possibly swapped) stills/clips, and copying the stale render just tripped
  // the "rendered without N clips" banner immediately on a brand-new copy.
  let toCopy = srcAssets.filter((a) => a.kind !== "render");
  // #96: a resume inherits the ancestor's IMAGES wholesale, including real
  // archival stills sourced under an older profile. The operator set
  // archivalStrength:"off" + visualMode:"ai_images" and still got 23 of 102
  // shots as real photography — none of them generated by this run at all
  // (styleSource/engineRequested/engineServed were all null, the tell), because
  // they were COPIED from a grandparent created before the setting changed.
  // archivalImagePolicy is correct; the sourcing never re-ran to be governed by
  // it. So when the new production forbids sourcing, the sourced stills don't
  // come across — the pipeline regenerates those shots under the current policy.
  if (opts.dropSourcedStills) {
    toCopy = toCopy.filter(
      (a) => !(a.kind === "image" && imageSourceKind((a.meta ?? {}) as Record<string, unknown>) === "sourced"),
    );
  }
  if (toCopy.length) {
    await tx.insert(assets).values(
      toCopy.map((a) => ({
        id: ulid(),
        productionId: newId,
        kind: a.kind,
        idx: a.idx,
        storageKey: a.storageKey,
        mimeType: a.mimeType,
        durationSec: a.durationSec,
        meta: a.meta,
      })),
    );
  }
  const srcThumbs = await tx.select().from(thumbnails).where(eq(thumbnails.productionId, sourceId));
  if (srcThumbs.length) {
    await tx.insert(thumbnails).values(
      srcThumbs.map((t) => ({
        id: ulid(),
        productionId: newId,
        storageKey: t.storageKey,
        selected: t.selected,
        predictedCtr: t.predictedCtr,
      })),
    );
  }
  // Music (2026-07-19): copy the picked track too — without this a corrected
  // copy / resume rendered SILENT (the render found no production_music row and
  // dropped the bed) even though the source's cut had music.
  const srcMusic = await tx.select().from(productionMusic).where(eq(productionMusic.productionId, sourceId));
  if (srcMusic.length) {
    await tx.insert(productionMusic).values(
      srcMusic.map((m) => ({
        id: ulid(),
        productionId: newId,
        storageKey: m.storageKey,
        mimeType: m.mimeType,
        name: m.name,
        durationSec: m.durationSec,
        mood: m.mood,
        prompt: m.prompt,
        engine: m.engine,
        selected: m.selected,
      })),
    );
  }
}

