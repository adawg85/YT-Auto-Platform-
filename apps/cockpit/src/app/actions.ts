/** Shared greenlight body: create the production + kick off the pipeline. */
async function greenlightInternal(ideaId: string, allowDuplicate: boolean) {
  const { db } = await getAppContext();
  const [idea] = await db.select().from(ideas).where(eq(ideas.id, ideaId));
  if (!idea) throw new Error("Idea not found");

  // Remediation §2.1: don't ship a SECOND video for an idea that already
  // published one — unless the operator explicitly overrides (a legitimate re-do
  // of a failed run). "Make a corrected copy" is the path for re-cutting a good one.
  if (!allowDuplicate) {
    const dupe = await publishedVideoForIdea(db, ideaId);
    if (dupe) {
      throw new Error(
        `This idea already has a published video (${dupe.providerVideoId}). Use "Make a corrected copy" to re-cut it, or re-greenlight with the duplicate override to intentionally publish a second upload.`,
      );
    }
  }

  // #101: seed who narrates from the CHANNEL default, so a human-narrated
  // channel doesn't need the per-video toggle flipped on every greenlight.
  const [glDna] = await db.select().from(channelDna).where(eq(channelDna.channelId, idea.channelId));
  const [glChannel] = await db.select().from(channels).where(eq(channels.id, idea.channelId));
  const glVoiceSource = resolveProductionProfile(glDna?.productionProfile ?? null, {
    contentFormat: glChannel?.contentFormat,
  }).voiceSource;

  const productionId = ulid();
  await db.insert(productions).values({
    id: productionId,
    ideaId,
    channelId: idea.channelId,
    status: "greenlit",
    allowDuplicate,
    voiceSource: glVoiceSource,
  });
  await db.update(ideas).set({ status: "greenlit" }).where(eq(ideas.id, ideaId));
  await inngest.send({ name: "production/greenlit", data: { productionId, attempt: "0" } });
  revalidatePath("/ideas");
  revalidatePath("/gates");
  revalidatePath(`/channels/${idea.channelId}`); // #19: also the Plan tab
}

/** Greenlight: create the production and kick off the durable pipeline. Blocks a
 * duplicate publish of an already-published idea (remediation §2.1). */
export async function greenlightAction(ideaId: string) {
  await greenlightInternal(ideaId, false);
}

/** Explicit operator override (remediation §2.1): greenlight even though the idea
 * already published a video — an intentional second upload. */
export async function greenlightAllowDuplicateAction(ideaId: string) {
  await greenlightInternal(ideaId, true);
}

/** Artifact groups the operator can keep or discard when halting a production. */
export type HaltDiscard = "script" | "voiceover" | "images" | "render" | "thumbnails";

/**
 * Halt a production from ANY stage and return its idea to the greenlightable
 * pool (idea → `scored`), preserving the production as a `halted` draft. The
 * operator chooses which produced artifacts to discard; kept ones stay attached
 * for a future resume. Cancels any in-flight pipeline run via `production/halt`
 * (the pipeline's `cancelOn`). Never deletes the production row — a mid-flight
 * hard delete would make child-insert steps throw and retry-storm.
 */
export async function haltProductionAction(productionId: string, discard: HaltDiscard[] = []) {
  const { db } = await getAppContext();
  const [production] = await db.select().from(productions).where(eq(productions.id, productionId));
  if (!production) throw new Error("Production not found");

  const drop = new Set(discard);
  await db.transaction(async (tx) => {
    if (drop.has("script")) {
      await tx.delete(scriptDrafts).where(eq(scriptDrafts.productionId, productionId));
    }
    if (drop.has("voiceover")) {
      await tx
        .delete(assets)
        .where(and(eq(assets.productionId, productionId), eq(assets.kind, "voiceover")));
    }
    if (drop.has("images")) {
      await tx.delete(assets).where(and(eq(assets.productionId, productionId), eq(assets.kind, "image")));
    }
    if (drop.has("render")) {
      await tx.delete(assets).where(and(eq(assets.productionId, productionId), eq(assets.kind, "render")));
    }
    if (drop.has("thumbnails")) {
      await tx.delete(thumbnails).where(eq(thumbnails.productionId, productionId));
    }
    // any gate still waiting is abandoned — expire it so it drops out of Review
    await tx
      .update(reviewGates)
      .set({ status: "expired" })
      .where(and(eq(reviewGates.productionId, productionId), eq(reviewGates.status, "pending")));
    await tx
      .update(productions)
      .set({ status: "halted", currentGateId: null, inngestRunId: null, failureReason: null })
      .where(eq(productions.id, productionId));
    // hand the idea back to the greenlightable pool (pre-greenlight = "scored")
    await tx.update(ideas).set({ status: "scored" }).where(eq(ideas.id, production.ideaId));
  });

  // stop the durable run if one is live (no-op if it already finished/died)
  await inngest.send({ name: "production/halt", data: { productionId } });

  revalidatePath(`/productions/${productionId}`);
  revalidatePath("/ideas");
  revalidatePath("/gates");
}

/**
 * Resume a halted production (BACKLOG #15 Land 2): reuse its kept script on a
 * fresh production and regenerate media. The pipeline detects the pre-seeded
 * script draft and skips drafting + the script gate. Media (voiceover/images/
 * render) is generated new under the new id, so no cross-id storage-key reuse.
 */
export async function resumeProductionAction(haltedProductionId: string) {
  const { db } = await getAppContext();
  const [halted] = await db.select().from(productions).where(eq(productions.id, haltedProductionId));
  if (!halted) throw new Error("Production not found");
  // A production halted EARLY (e.g. around planning, before the script gate) has
  // no draft. That's fine — reinstate it as a fresh production from the idea,
  // reusing whatever media survived the halt. A later halt (script exists) reuses
  // the script and skips drafting + the script gate.
  const [draft] = await db
    .select()
    .from(scriptDrafts)
    .where(eq(scriptDrafts.productionId, haltedProductionId))
    .orderBy(desc(scriptDrafts.version))
    .limit(1);

  // #96: the carried per-video profile must not FREEZE the channel's config at
  // the moment of the halt. #94 made resume carry productionProfile forward (so
  // the profile LLM and its gate don't re-run) — but carried alone it shadowed
  // every axis the operator changed since, and archivalStrength:"off" set after
  // the ancestor was created never took effect. Merge the per-video decisions
  // OVER the channel's CURRENT profile: live config wins for anything the video
  // didn't deliberately override, per-video overrides still survive.
  const [resumeChannel] = await db.select().from(channels).where(eq(channels.id, halted.channelId));
  const [resumeDna] = await db.select().from(channelDna).where(eq(channelDna.channelId, halted.channelId));
  const resumeProfile = mergeProductionProfile(
    (resumeDna?.productionProfile ?? null) as Partial<ProductionProfile> | null,
    (halted.productionProfile ?? null) as Partial<ProductionProfile> | null,
    { contentFormat: resumeChannel?.contentFormat },
  );
  // when the resolved profile forbids real photography, the ancestor's sourced
  // stills must not ride along — see copyProductionMedia (#96)
  const dropSourcedStills = !archivalImagePolicy(resumeProfile).attemptSourcing;

  const newId = ulid();
  await db.transaction(async (tx) => {
    await tx.insert(productions).values({
      id: newId,
      ideaId: halted.ideaId,
      channelId: halted.channelId,
      status: "greenlit",
      // reuse the fingerprint so the anti-clone check sees the same substance
      substanceFingerprint: halted.substanceFingerprint,
      // #94: carry the halted run's PER-VIDEO settings — resume used to reset
      // them to channel defaults, which quietly changed what the resumed video
      // is (the corrected-copy path has always carried them; resume didn't).
      //  - externalScript: without it an OPERATOR-AUTHORED production stops
      //    being one. It re-presents the script gate that author_script skips,
      //    the image-prompt BUILDER rewrites every authored imagePrompt instead
      //    of using it verbatim, and authored motionPrompts are ignored — so a
      //    resume silently discarded 126 authored prompts (and, with them,
      //    #93's authored-prompt style path).
      //  - productionProfile: without it the propose-profile-tweaks LLM re-runs
      //    and mints a FRESH profile_review gate on a video whose profile was
      //    already decided — how the reported production ended up parked in a
      //    review state at all. Carrying it makes the pipeline reuse the
      //    decision and skip both the spend and the gate.
      externalScript: halted.externalScript,
      // P6: carry the three AUTHORING INTENTIONS as a unit. #94 lost the single
      // flag here and silently un-authored the production; a struct cannot be
      // half-carried, and a partial pass (script yours, prompts the platform's)
      // survives the copy intact.
      ...resolveAuthoringIntents(halted),
      // #96: the MERGED profile (channel-current + this video's overrides), not
      // the ancestor's frozen snapshot — see the merge above.
      productionProfile: resumeProfile,
      voiceSource: halted.voiceSource,
      voiceVolume: halted.voiceVolume,
      musicVolume: halted.musicVolume,
      personaId: halted.personaId,
      personaVersion: halted.personaVersion,
      styleId: halted.styleId,
      styleVersion: halted.styleVersion,
    });
    // pre-seed the reused script as v1 — the pipeline picks this up and skips
    // drafting + the script gate. Skipped when there was no script (fresh draft).
    if (draft) {
      await tx.insert(scriptDrafts).values({
        id: ulid(),
        productionId: newId,
        version: 1,
        hookTemplateId: draft.hookTemplateId,
        hookText: draft.hookText,
        beats: draft.beats,
        fullText: draft.fullText,
        wordCount: draft.wordCount,
        // carry the Visual Director's SHOT CUT (2026-07-19): without it the copy
        // re-ran the director, got a slightly different cut, and the copied
        // stills no longer aligned — so it regenerated them (a pile of Sonnet
        // calls) instead of reusing all N and going straight to the visuals gate.
        directedSequence: draft.directedSequence,
      });
    }
    // Land 3: reuse whatever media survived the halt keep/discard.
    await copyProductionMedia(tx, haltedProductionId, newId, { dropSourcedStills });
    await tx.update(ideas).set({ status: "greenlit" }).where(eq(ideas.id, halted.ideaId));
  });
  await inngest.send({ name: "production/greenlit", data: { productionId: newId, attempt: "0" } });
  revalidatePath("/ideas");
  redirect(`/productions/${newId}`);
}

/**
 * "Make a corrected copy" of an ALREADY-PUBLISHED video (2026-07-19 operator:
 * a published Krypton short shipped with a stray real clip and there was no way
 * back in — a published production is intentionally locked). YouTube cannot
 * replace a live video's file, so the fix ships as a NEW upload: this mints a
 * fresh production from the same script + a copy of every shot/clip, so the
 * operator re-animates the bad shot, re-renders, and publishes anew.
 *
 * `deleteOld` (opt-in, default off) records intent to remove the superseded
 * original's live YouTube video once the corrected copy goes live — handled by
 * the worker's supersede-cleanup on `production/published`, NOT here (nothing is
 * deleted until the replacement is actually out).
 */
export async function correctPublishedProductionAction(
  publishedProductionId: string,
  deleteOld: boolean = false,
  // "fix" (default): reuse everything — script, voiceover, stills, clips — and
  // land at the visuals gate to swap what's wrong. "rebuild": keep the approved
  // script but regenerate ALL visuals fresh. Both skip the script gate.
  mode: "fix" | "rebuild" = "fix",
) {
  const { db } = await getAppContext();
  const [orig] = await db.select().from(productions).where(eq(productions.id, publishedProductionId));
  if (!orig) throw new Error("Production not found");
  if (!["published", "scheduled"].includes(orig.status)) {
    throw new Error(
      `Production is ${orig.status} — "Make a corrected copy" is for a published/scheduled video. Use Retry-from-stage or Resume for one still in production.`,
    );
  }
  const [draft] = await db
    .select()
    .from(scriptDrafts)
    .where(eq(scriptDrafts.productionId, publishedProductionId))
    .orderBy(desc(scriptDrafts.version))
    .limit(1);
  // A corrected copy MUST carry the approved script forward — that seed is what
  // makes the pipeline skip drafting + the script gate. Without it the copy would
  // silently re-draft (a pile of Sonnet calls) and land on script review, which
  // is exactly the symptom the operator kept hitting. Fail loudly instead.
  if (!draft) {
    throw new Error(
      "Cannot make a corrected copy: this published video has no stored script draft to reuse. Tell Claude — the original's script row is missing.",
    );
  }

  const newId = ulid();
  await db.transaction(async (tx) => {
    await tx.insert(productions).values({
      id: newId,
      ideaId: orig.ideaId,
      channelId: orig.channelId,
      status: "greenlit",
      substanceFingerprint: orig.substanceFingerprint,
      // Carry the approved video's per-video settings so the corrected copy is
      // a faithful re-cut AND doesn't re-spend (2026-07-19): keeping the
      // productionProfile skips the propose-profile-tweaks LLM step, and the
      // audio-mix dials + voice source stay as approved.
      productionProfile: orig.productionProfile,
      // P6: same reason as resume — a corrected copy of an AUTHORED video stays
      // authored, so the builder never rewrites prompts the operator owns.
      externalScript: orig.externalScript,
      ...resolveAuthoringIntents(orig),
      voiceSource: orig.voiceSource,
      voiceVolume: orig.voiceVolume,
      musicVolume: orig.musicVolume,
      personaId: orig.personaId,
      personaVersion: orig.personaVersion,
      styleId: orig.styleId,
      styleVersion: orig.styleVersion,
      // provenance + (opt-in) auto-remove the old live upload once this is live
      supersedesProductionId: publishedProductionId,
      supersedeDeleteOld: deleteOld,
    });
    if (draft) {
      await tx.insert(scriptDrafts).values({
        id: ulid(),
        productionId: newId,
        version: 1,
        hookTemplateId: draft.hookTemplateId,
        hookText: draft.hookText,
        beats: draft.beats,
        fullText: draft.fullText,
        wordCount: draft.wordCount,
        // carry the Visual Director's SHOT CUT (2026-07-19): without it the copy
        // re-ran the director, got a slightly different cut, and the copied
        // stills no longer aligned — so it regenerated them (a pile of Sonnet
        // calls) instead of reusing all N and going straight to the visuals gate.
        directedSequence: draft.directedSequence,
      });
    }
    // "fix" copies the voiceover/stills/clips/render/music so they're reused;
    // "rebuild" leaves them out so the pipeline regenerates the visuals fresh
    // (the script is still reused, so the script gate is skipped either way).
    if (mode === "fix") await copyProductionMedia(tx, publishedProductionId, newId);
    await tx.update(ideas).set({ status: "greenlit" }).where(eq(ideas.id, orig.ideaId));
  });
  // Verify the corrected-copy marker actually landed before firing the pipeline.
  // If supersedes_production_id didn't persist (missing column / silent no-op),
  // the pipeline treats this as a normal production and re-runs script + profile
  // + checks, firing Sonnet — the failure the operator kept hitting. Fail loud
  // here instead of shipping a "copy" that behaves like a full re-run.
  const [verify] = await db
    .select({ supersedes: productions.supersedesProductionId })
    .from(productions)
    .where(eq(productions.id, newId));
  if (!verify?.supersedes) {
    throw new Error(
      "Corrected copy failed to record its link to the original — it would re-run the whole pipeline (and bill Sonnet). Not started. Tell Claude: supersedes_production_id didn't persist.",
    );
  }
  await inngest.send({ name: "production/greenlit", data: { productionId: newId, attempt: "0" } });
  revalidatePath(`/productions/${publishedProductionId}`);
  redirect(`/productions/${newId}`);
}

