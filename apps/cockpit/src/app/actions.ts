// ── Stage re-entry (2026-08-04 operator design session) ───────────────────
// HOLD / CONTINUE / REOPEN, all IN PLACE on one production row. These replace
// the old recovery shape where every verb re-fired the pipeline from the top
// and `resume_production` minted a sibling production (the lineage behind
// #94, #96 and #97). `halt_production` is already the Hold button; these are
// the other two thirds.

/** What a production actually has built, for the stage-machine decisions. */
async function artifactCountsFor(db: Db, productionId: string): Promise<ArtifactCounts & { script: boolean }> {
  const rows = await db
    .select({ kind: assets.kind })
    .from(assets)
    .where(eq(assets.productionId, productionId));
  const thumbs = await db
    .select({ id: thumbnails.id })
    .from(thumbnails)
    .where(eq(thumbnails.productionId, productionId));
  const music = await db
    .select({ id: productionMusic.id })
    .from(productionMusic)
    .where(eq(productionMusic.productionId, productionId));
  const [draft] = await db
    .select({ id: scriptDrafts.id })
    .from(scriptDrafts)
    .where(eq(scriptDrafts.productionId, productionId))
    .limit(1);
  const n = (k: string) => rows.filter((r) => r.kind === k).length;
  return {
    voiceover: n("voiceover"),
    takes: n("voiceover_take"), // #125: so the reopen preview can say they're safe
    images: n("image"),
    clips: n("video_clip"),
    render: n("render"),
    thumbnails: thumbs.length,
    music: music.length,
    script: Boolean(draft),
  };
}

/**
 * CONTINUE — resume a held production from exactly where it stopped.
 *
 * Not a retry: nothing is deleted, nothing is re-billed, and the status lands on
 * the work that EXISTS rather than upstream of it (#98's lesson — a built,
 * human-approved production must never present as if it were back at the start).
 */
export async function continueProductionAction(productionId: string): Promise<{ error?: string }> {
  const { db } = await getAppContext();
  const [prod] = await db.select().from(productions).where(eq(productions.id, productionId));
  if (!prod) return { error: "Production not found" };
  if (!["halted", "on_hold", "failed"].includes(prod.status)) {
    return {
      error: `Production is ${prod.status} — Continue resumes a held or blocked production. It is already moving.`,
    };
  }
  const have = await artifactCountsFor(db, productionId);
  const status = continueStatusFor(have);

  await db.transaction(async (tx) => {
    await tx
      .update(productions)
      .set({
        status: status as typeof prod.status,
        failureReason: null,
        currentGateId: null,
        inngestRunId: null,
      })
      .where(eq(productions.id, productionId));
    await tx.update(ideas).set({ status: "greenlit" }).where(eq(ideas.id, prod.ideaId));
  });
  await inngest.send({
    name: "production/greenlit",
    data: { productionId, attempt: `continue-${ulid()}` },
  });
  revalidatePath(`/productions/${productionId}`);
  revalidatePath("/gates");
  return {};
}

/**
 * REOPEN — go back to a named stage, in place.
 *
 * `mode: "reopen"` keeps that stage's own output so the operator can refine it
 * (fix three shots, re-prompt one); `mode: "clean"` rebuilds it from scratch.
 * Either way everything DOWNSTREAM is marked stale and shown as such, and is
 * destroyed only when the reopened stage actually produces new output — so this
 * call is reversible via `cancelReopenAction`.
 *
 * Returns the impact so the caller can render the confirmation; pass
 * `confirm: false` to preview it without changing anything.
 */
export async function reopenStageAction(
  productionId: string,
  stage: ProductionStage,
  opts: { mode?: ReopenMode; confirm?: boolean } = {},
): Promise<{
  error?: string;
  impact?: ReturnType<typeof reopenImpact>;
  /** #127: this call AMENDED a reopen of the same stage that was still in flight */
  amendedPreviousReopen?: { previousMode: ReopenMode | null; supersededGateIds: string[] };
}> {
  const mode = opts.mode ?? "reopen";
  const { db } = await getAppContext();
  const [prod] = await db.select().from(productions).where(eq(productions.id, productionId));
  if (!prod) return { error: "Production not found" };
  if (["published", "published_unverified", "analysing", "retired", "superseded"].includes(prod.status)) {
    return {
      error: `Production is ${prod.status} — a published video can't be reopened. Use correct_published_production, which ships the fix as a new upload (YouTube can't replace a live file).`,
    };
  }
  // #117: reopening 'script' on an AUTHORED production is provably inert — no
  // script_review gate is ever presented (gateRequired skips it for authored
  // scripts unless the channel names it), so the pipeline just re-emits the
  // authored draft verbatim and returns to where it was; worse, mode 'clean'
  // DELETES the authored draft and forces a full LLM redraft. Refuse with the
  // real path instead of accepting a call that silently does nothing.
  if (stage === "script" && resolveAuthoringIntents(prod).scriptAuthored) {
    const [dnaRow] = await db.select().from(channelDna).where(eq(channelDna.channelId, prod.channelId));
    const profile = resolveProductionProfile(prod.productionProfile ?? dnaRow?.productionProfile ?? null);
    const gateWouldPresent = gateRequired({
      gate: "script_review",
      impliedByDefault: false,
      declared: profile.gates,
    });
    if (!gateWouldPresent) {
      return {
        error:
          "This production's script is OPERATOR-AUTHORED, so reopening 'script' presents no review gate — the pipeline would just re-emit your authored draft unchanged and cycle back to where it is now" +
          (mode === "clean" ? " (and mode 'clean' would DELETE the authored draft and hand the script to the LLM writer — almost certainly not what you want)" : "") +
          ". To change the narration or visual direction, use edit_script_beats — it works at the script_review AND voiceover_recording gates, edits beats by index, and read the current text with get_script first. To replace the script wholesale, halt and author_script a fresh production.",
      };
    }
  }
  const have = await artifactCountsFor(db, productionId);
  const impact = reopenImpact(stage, have, mode);
  // preview only — the caller wants the warning before committing
  if (opts.confirm === false) return { impact };

  // #127: a SECOND reopen of the same stage is an amendment — "change my mind
  // about the mode" — not a second, parallel reopen. It is also a realistic path,
  // since #125's assemblyWarning tells the caller to follow a mode:'reopen' with
  // mode:'clean'. It cannot be made a no-op (the first run may already have
  // consumed the marker and be parked at its gate), so what matters is that it
  // supersedes rather than stacks: the pending gates are expired here, and any
  // gate the earlier run opens LATER is superseded at creation by openReviewGate.
  // Report it so the caller sees an amendment, not a duplicate.
  const amending =
    prod.reopenedStage === stage || prod.status === (statusForStage(stage) as typeof prod.status);
  const pendingBefore = await db
    .select({ id: reviewGates.id })
    .from(reviewGates)
    .where(and(eq(reviewGates.productionId, productionId), eq(reviewGates.status, "pending")));

  await db.transaction(async (tx) => {
    await tx
      .update(reviewGates)
      .set({ status: "expired" })
      .where(and(eq(reviewGates.productionId, productionId), eq(reviewGates.status, "pending")));
    await tx
      .update(productions)
      .set({
        status: statusForStage(stage) as typeof prod.status,
        reopenedStage: stage,
        reopenMode: mode,
        reopenedAt: new Date(),
        failureReason: null,
        currentGateId: null,
        inngestRunId: null,
      })
      .where(eq(productions.id, productionId));
    await tx.update(ideas).set({ status: "greenlit" }).where(eq(ideas.id, prod.ideaId));
  });
  // the operator decision log is the editorial record — a reopen destroys work,
  // so what was reopened, in which mode, and what it put at risk is written down
  await db.insert(channelDecisions).values({
    id: ulid(),
    channelId: prod.channelId,
    kind: "operator_steer",
    actor: "operator",
    summary: `Reopened ${stage} (${mode}) on production ${productionId}${amending ? " — amended the previous reopen of this stage" : ""}`,
    detail: {
      productionId,
      stage,
      mode,
      staleStages: impact.staleStages,
      discards: impact.discards,
      keeps: impact.keeps,
      ...(amending
        ? { amendedPreviousReopen: true, previousMode: prod.reopenMode, supersededGateIds: pendingBefore.map((g) => g.id) }
        : {}),
    },
  });
  // FIRE THE PIPELINE. Without this, reopen wrote the target stage's status and
  // the stale marker and then nothing ran: the production sat in a working
  // status with no live run, no failureReason, and `blocked: null` (because
  // `producing_assets` is not a blocked status) — indistinguishable from "still
  // going" while it was in fact wedged forever. It also could not be recovered,
  // since continue/retry/force_forward all refuse a production that looks
  // in-flight. Every other in-place verb dispatches; this one silently did not.
  //
  // The pipeline's `sweep-stale-stages` step reads the marker written above and
  // deletes the stale output at the START of this run, so re-dispatching is what
  // makes the deferred deletion (and therefore cancel_reopen) work at all.
  await inngest.send({
    name: "production/greenlit",
    data: { productionId, attempt: `reopen-${stage}-${ulid()}` },
  });
  revalidatePath(`/productions/${productionId}`);
  revalidatePath("/gates");
  return {
    impact,
    ...(amending
      ? {
          amendedPreviousReopen: {
            previousMode: (prod.reopenMode as ReopenMode | null) ?? null,
            supersededGateIds: pendingBefore.map((g) => g.id),
          },
        }
      : {}),
  };
}

/**
 * CANCEL REOPEN — undo a reopen that hasn't run yet.
 *
 * This is the whole reason deletion is deferred: reopening is often diagnostic
 * ("I thought it was the voiceover, it was the resume path"), and a diagnostic
 * action must be reversible. Nothing was destroyed, so this just clears the
 * marker and un-stales the downstream work.
 */
export async function cancelReopenAction(productionId: string): Promise<{ error?: string }> {
  const { db } = await getAppContext();
  const [prod] = await db.select().from(productions).where(eq(productions.id, productionId));
  if (!prod) return { error: "Production not found" };
  if (!prod.reopenedStage) return { error: "No reopen is in flight on this production." };
  const have = await artifactCountsFor(db, productionId);
  await db
    .update(productions)
    .set({
      reopenedStage: null,
      reopenMode: null,
      reopenedAt: null,
      status: continueStatusFor(have) as typeof prod.status,
    })
    .where(eq(productions.id, productionId));
  revalidatePath(`/productions/${productionId}`);
  return {};
}

/**
 * Reattach a production to a video that was uploaded OUTSIDE the platform, and
 * sync its state from YouTube (2026-08-05).
 *
 * Manual upload is a legitimate, recurring path — an unverified channel can't
 * take a custom thumbnail via the API, and a long-form upload can die on the
 * worker — and until now the only way back was the `sync_publication_from_youtube`
 * MCP tool. A production left with a publication row and no providerVideoId
 * sits in `scheduled` forever, invisible to analytics and flagged by
 * get_diagnostics as a stuck upload.
 *
 * Shared implementation: the MCP tool now calls this, so the cockpit button and
 * Claude-in-chat can never drift apart.
 */
export type SyncPublicationResult = {
  error?: string;
  changed?: boolean;
  privacyStatus?: string;
  publishedAt?: string;
  scheduledFor?: string | null;
  reingestTriggered?: boolean;
  url?: string | null;
  /** #77: the video's CURRENT YouTube snippet title (Studio edits visible) */
  liveTitle?: string | null;
  /** #77: set when the live title diverges from the authored title */
  titleDriftNote?: string;
  note?: string;
};

export async function syncPublicationFromYouTubeAction(
  productionId: string,
  providerVideoIdOrUrl?: string,
): Promise<SyncPublicationResult> {
  const { db, providers } = await getAppContext();

  let supplied: string | undefined;
  if (providerVideoIdOrUrl?.trim()) {
    const parsed = parseYouTubeVideoId(providerVideoIdOrUrl);
    if (!parsed) {
      return { error: "That doesn't look like a YouTube video link or id. Paste the watch URL or the 11-character id." };
    }
    supplied = parsed;
  }

  const [prod] = await db
    .select({
      id: productions.id,
      channelId: productions.channelId,
      status: productions.status,
      authoredMetadata: productions.authoredMetadata, // #77: for the title-drift note
    })
    .from(productions)
    .where(eq(productions.id, productionId))
    .limit(1);
  if (!prod) return { error: "Production not found" };

  const [pub] = await db
    .select()
    .from(publications)
    .where(eq(publications.productionId, productionId))
    .orderBy(desc(publications.createdAt))
    .limit(1);
  if (!pub) return { error: "No publication row for this production — nothing to sync." };

  const videoId = supplied ?? pub.providerVideoId;
  if (!videoId) {
    return { error: "This record has no YouTube video id — paste the link of the video you uploaded." };
  }

  let live: Awaited<ReturnType<typeof providers.publish.videoStatus>>;
  try {
    live = await providers.publish.videoStatus({ channelId: prod.channelId, providerVideoId: videoId });
  } catch (e) {
    return { error: `Provider read failed: ${e instanceof Error ? e.message : String(e)}` };
  }
  if (live.state === "unknown") {
    return { changed: false, note: "Provider couldn't resolve the video (no YouTube credentials / mock mode) — no change made." };
  }
  if (live.state === "missing") {
    return { error: `YouTube has no video with id ${videoId} — check the link. (Use reconcile_publications to demote a phantom record.)` };
  }

  // Attach a newly-supplied id (external upload the platform never recorded).
  const url = `https://www.youtube.com/watch?v=${videoId}`;
  const attachedId = !pub.providerVideoId && supplied ? supplied : undefined;
  if (attachedId) {
    await db.update(publications).set({ providerVideoId: attachedId, url }).where(eq(publications.id, pub.id));
  }

  if (live.privacyStatus !== "public") {
    // Uploaded but not public yet — reflect the id/scheduled state, don't go live.
    if (live.publishAt) {
      await db
        .update(publications)
        .set({ privacyStatus: "scheduled", scheduledFor: new Date(live.publishAt) })
        .where(eq(publications.id, pub.id));
    }
    revalidatePath(`/productions/${productionId}`);
    return {
      changed: Boolean(attachedId || live.publishAt),
      privacyStatus: live.privacyStatus,
      scheduledFor: live.publishAt ?? null,
      url,
      liveTitle: live.title ?? null, // #77: Studio-side packaging is visible now
      note: `Video is ${live.privacyStatus} on YouTube, not public yet — ${live.publishAt ? "scheduled state synced" : "linked, left as-is"}. Nothing marked live.`,
    };
  }

  const realPublishedAt = resolveGoLivePublishedAt({
    remotePublishedAt: live.publishedAt,
    scheduledFor: pub.scheduledFor,
    now: new Date(),
  });
  const wasAlreadyPublished = Boolean(pub.publishedAt);
  await markPublicationLive(db, {
    publicationId: pub.id,
    productionId,
    publishedAt: realPublishedAt,
    emitEvents: !wasAlreadyPublished,
  });
  const movedBackward =
    !wasAlreadyPublished ||
    (pub.publishedAt != null && realPublishedAt.getTime() < new Date(pub.publishedAt).getTime());
  if (movedBackward) {
    await inngest.send({ name: "analytics/ingest.requested", data: { channelId: prod.channelId } });
  }
  await db.insert(channelDecisions).values({
    id: ulid(),
    channelId: prod.channelId,
    kind: "operator_steer",
    actor: "operator",
    summary: `Synced production ${productionId} from YouTube (marked live)`,
    detail: {
      productionId,
      publicationId: pub.id,
      providerVideoId: videoId,
      action: "sync_from_youtube",
      externallyUploaded: Boolean(attachedId),
      publishedAt: realPublishedAt.toISOString(),
      previousPublishedAt: pub.publishedAt ? new Date(pub.publishedAt).toISOString() : null,
    },
  });
  revalidatePath(`/productions/${productionId}`);
  // #77: report the LIVE title so a Studio-side retitle is visible over MCP;
  // when it drifts from the authored title, say so (informational — YouTube is
  // the source of truth for live packaging, authoredMetadata is the intent).
  const authoredTitle = (prod.authoredMetadata as { title?: string } | null)?.title?.trim();
  const titleDrift = Boolean(live.title && authoredTitle && live.title.trim() !== authoredTitle);
  return {
    changed: true,
    privacyStatus: "public",
    publishedAt: realPublishedAt.toISOString(),
    reingestTriggered: movedBackward,
    url,
    liveTitle: live.title ?? null,
    ...(titleDrift
      ? { titleDriftNote: `Live YouTube title ("${live.title}") differs from the authored title ("${authoredTitle}") — edited in Studio, or push an update with set_publication_metadata.` }
      : {}),
    note: wasAlreadyPublished
      ? "publishedAt corrected to YouTube's real value."
      : "Marked live from YouTube with the real publishedAt; post-publish analysis + analytics ingest triggered.",
  };
}
